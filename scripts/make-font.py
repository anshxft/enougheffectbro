"""Bake the Archivo variable font into what the 3D scene needs.

  python -I scripts/make-font.py <path to Archivo[wdth,wght].ttf>

Writes:
  public/fonts/archivo-expanded-800.ttf  static wdth=125 wght=800, Latin subset (troika text in WebGL can't read woff2/variable axes)
  src/three/glyph-a.ts                   SVG path of the "A" glyph, extruded into the prism
"""
import sys
from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.subset import Options, Subsetter
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

ROOT = Path(__file__).resolve().parent.parent
WDTH, WGHT = 125, 800

font = instantiateVariableFont(TTFont(sys.argv[1]), {"wdth": WDTH, "wght": WGHT})

opts = Options()
opts.layout_features = ["kern", "liga"]
sub = Subsetter(opts)
sub.populate(text="".join(chr(c) for c in range(0x20, 0x7F)) + "·—’“”…↗←→")
sub.subset(font)

out = ROOT / "public/fonts/archivo-expanded-800.ttf"
out.parent.mkdir(parents=True, exist_ok=True)
font.save(out)

glyphs = font.getGlyphSet()
name = font.getBestCmap()[ord("A")]
pen = SVGPathPen(glyphs)
glyphs[name].draw(pen)
upm = font["head"].unitsPerEm
ts = ROOT / "src/three/glyph-a.ts"
ts.parent.mkdir(parents=True, exist_ok=True)
ts.write_text(
    "// Generated by scripts/make-font.py — Archivo wdth=125 wght=800, font units (y up).\n"
    f"export const GLYPH_A = {{ path: '{pen.getCommands()}', advance: {glyphs[name].width}, unitsPerEm: {upm} }}\n",
    encoding="utf-8",
)
print(out, out.stat().st_size, "bytes;", ts)
